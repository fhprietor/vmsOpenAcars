        [TestMethod]
        public void Reprompt_AfterPushback_OnlyWhenTheNewStartPointChangesTheRoute()
        {
            // Puestos reales del vuelo: el de salida (BST 21:45:47), el fin del pushback (freno
            // puesto 21:52:39), el arranque del rodaje (── TAXI OUT ── 21:55:54) y el primer TXI
            // (21:56:18), ya en la calle B9. La propuesta del grafo desde cada uno:
            var target = Runways().First(r => r.Name == "14R");
            string fromStand = TaxiGraph.Suggest(Seg(), 4.697740, -74.138390,
                                                 target.TLat, target.TLon).Text;
            string afterPush = TaxiGraph.Suggest(Seg(), 4.69788, -74.13721,
                                                 target.TLat, target.TLon).Text;
            string atTaxiOut = TaxiGraph.Suggest(Seg(), 4.69812, -74.13751,
                                                 target.TLat, target.TLon).Text;
            string alreadyMoving = TaxiGraph.Suggest(Seg(), 4.69887, -74.13738,
                                                     target.TLat, target.TLon).Text;

            Assert.AreEqual("C P G N H M K K2 K1", fromStand);

            // El pushback de este vuelo movió el avión 432 ft y **no** cambió la primera calle:
            // volver a abrir el popup para proponer lo mismo sería ruido.
            Assert.IsTrue(TaxiRoutePlan.SameRoute(fromStand, afterPush),
                          $"fin del pushback propone lo mismo: {afterPush}");
            Assert.IsTrue(TaxiRoutePlan.SameRoute(fromStand, atTaxiOut),
                          $"arranque del rodaje propone lo mismo: {atTaxiOut}");

            // Pero el segundo aviso es un aviso de verdad: en cuanto el avión ya está en otra
            // calle, la propuesta cambia. (Aquí, además, empeora —`B9 C P…` manda volver a C—,
            // que es exactamente por qué se recalcula **en el punto de inicio** y no rodando.)
            Assert.IsFalse(TaxiRoutePlan.SameRoute(fromStand, alreadyMoving),
                           $"rodando por B9 la propuesta ya es otra: {alreadyMoving}");
        }

