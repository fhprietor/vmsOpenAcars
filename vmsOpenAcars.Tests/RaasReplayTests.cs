                events.Add(Tuple.Create(Parse(kv.Item1), "[real]        " + kv.Item2));

            // Ruta que el grafo propone en el puesto de salida hasta el umbral de la 14R: es lo que
            // el piloto vería en el popup y aceptaría con EMPEZAR GUÍA.
            var target     = Runways().First(r => r.Name == "14R");
            var suggestion = TaxiGraph.Suggest(Seg(), trace[0].Lat, trace[0].Lon, target.TLat, target.TLon);
            string routeText = suggestion.Text;
            events.Add(Tuple.Create(Parse(trace[0].Time),
                "[guía]        RUTA SUGERIDA POR EL GRAFO: " + routeText +
                $"   (pista 14R, {suggestion.DistanceM:F0} m)"));

            var plan     = TaxiRoutePlan.Parse(routeText);
            var advisor  = new RaasAdvisor();
            var callouts = new List<RaasCalloutType>();
            DateTime? firstOnRunway = null;

            foreach (var p in trace)
            {
                bool onRunway = Runways().Any(r =>
                    GeoMath.DistanceToSegmentNm(p.Lat, p.Lon, r.TLat, r.TLon, r.ELat, r.ELon)
                    * GeoMath.MetersPerNm <= 45.0);
                if (onRunway && firstOnRunway == null) firstOnRunway = Parse(p.Time);

                string active = TaxiGraph.NearestName(Seg(), p.Lat, p.Lon, p.Hdg);

                Hs nearest = null; double nearestM = double.MaxValue; bool toward = false;
                foreach (var x in HoldShorts())
                {
                    double dm = GeoMath.DistanceNm(p.Lat, p.Lon, x.Lat, x.Lon) * GeoMath.MetersPerNm;
                    if (dm > 200.0 || dm >= nearestM) continue;
                    if (GeoMath.BearingDiffDeg(GeoMath.BearingDeg(p.Lat, p.Lon, x.Lat, x.Lon), p.Hdg) > 90.0)
                        continue;                                  // de través: no cuenta
                    nearest = x; nearestM = dm; toward = true;
                }

                var guidance = RaasAdvisor.ResolveGuidance(Seg(), plan, p.Lat, p.Lon, active);
                var callout  = advisor.Evaluate(new RaasAdvisor.Inputs
                {
                    OnRunway               = onRunway,
                    GroundSpeedKt          = p.Gs,
                    HoldShortRunway        = nearest?.Rwy,
                    HoldShortDistanceM     = nearest != null ? nearestM : double.NaN,
                    HeadingTowardHoldShort = toward,
                    ActiveTaxiway          = active,
                    Guidance               = guidance,
                    // Distancia recta al umbral de la 14R: es lo que distingue «voy por otra
                    // calle pero me acerco» de «me he perdido».
                    DistanceToRunwayM      = GeoMath.DistanceNm(p.Lat, p.Lon, target.TLat, target.TLon)
                                             * GeoMath.MetersPerNm
                }, Parse(p.Time));

                if (callout.Type != RaasCalloutType.None)
                {
                    callouts.Add(callout.Type);
                    events.Add(Tuple.Create(Parse(p.Time), "[RAAS]        " + Text(callout)));
                }
            }

            var lines = events.OrderBy(e => e.Item1)
                              .Select(e => e.Item1.ToString("HH:mm:ss") + "  " + e.Item2)
                              .ToList();
            File.WriteAllLines(Path.Combine(Path.GetTempPath(), "raas_replay_MNjR664.txt"), lines);

            Assert.IsTrue(routeText.StartsWith("C "), "la ruta sugerida arranca en la calle C: " + routeText);
            Assert.IsTrue(lines.Any(l => l.Contains("ESPERA ANTES DE PISTA 14R")),
                          "debe avisar del hold-short de la 14R");
            Assert.IsTrue(lines.Count > 20, "la repetición debe producir una secuencia completa");

            // La secuencia completa de avisos del rodaje real, que es lo que este banco existe para
            // vigilar: un giro, el hold-short (a 150 m y a 40 m), la insistencia al reanudar tras
            // los 135 s de espera, y la entrada en pista. Ni uno más.
            CollectionAssert.AreEqual(new[]
            {
                RaasCalloutType.TurnAhead,
                RaasCalloutType.HoldShortApproaching,
                RaasCalloutType.HoldShortStop,
                RaasCalloutType.HoldShortStop,
                RaasCalloutType.RouteComplete
            }, callouts, "cinco avisos en todo el rodaje, en este orden y sin ruido");

            // El piloto hizo la ruta de ATC (`C B9 B M K K1 V`) en vez de la del grafo
            // (`C P G N H M K K2 K1`) y aun así se acercaba a la 14R todo el tiempo: avisarle de
            // que estaba fuera de ruta era ruido (salía 8 veces en v0.9.14).
            Assert.IsFalse(lines.Any(l => l.Contains("FUERA DE RUTA")),
                           "yendo hacia la pista por otras calles no se avisa de desvío");

            var completions = events.Where(e => e.Item2.Contains("RUTA DE RODAJE COMPLETA")).ToList();
            Assert.AreEqual(1, completions.Count, "se anuncia una sola vez");
            Assert.IsTrue(firstOnRunway.HasValue, "la traza acaba dentro de la 14R");
            Assert.IsTrue(completions[0].Item1 >= firstOnRunway.Value,
                          "«ruta completa» es haber llegado a la pista, no agotar la lista de calles");
        }

        private static DateTime Parse(string t) => DateTime.ParseExact(
            t.Length > 8 ? t.Substring(11) : t, "HH:mm:ss", CultureInfo.InvariantCulture);

        // ── Formateo: las mismas claves que usa la aplicación ─────────────────────
        private static readonly Dictionary<string, string> Es = LoadEs();

        private static Dictionary<string, string> LoadEs()
        {
            foreach (string rel in new[]
            {
                @"Languages\es.json",
                @"..\..\..\vmsOpenAcars\bin\Debug\Languages\es.json",
                @"..\vmsOpenAcars\bin\Debug\Languages\es.json"
            })
            {
                try
                {
                    if (!File.Exists(rel)) continue;
                    // Se lee con regex en vez de con Newtonsoft para no añadir esa dependencia al
                    // proyecto de tests: el archivo de idioma es plano, clave -> texto.
                    var dict = new Dictionary<string, string>();
                    foreach (System.Text.RegularExpressions.Match m in
                             System.Text.RegularExpressions.Regex.Matches(
                                 File.ReadAllText(rel),
                                 "\"(?<k>[^\"]+)\"\\s*:\\s*\"(?<v>(?:[^\"\\\\]|\\\\.)*)\""))
                        dict[m.Groups["k"].Value] =
                            System.Text.RegularExpressions.Regex.Unescape(m.Groups["v"].Value);
                    if (dict.Count > 0) return dict;
                }
                catch { }
            }
            return new Dictionary<string, string>();
        }

        private static string T(string key, params object[] args)
        {
            string tpl;
            if (!Es.TryGetValue(key, out tpl))
                return key + (args.Length > 0 ? " " + string.Join(" ", args) : "");
            return args.Length > 0 ? string.Format(tpl, args) : tpl;
        }

        private static string Text(RaasCallout c)
        {
            int m = (int)Math.Round(c.DistanceM / 10.0) * 10;
            switch (c.Type)
            {
                case RaasCalloutType.HoldShortApproaching: return T("Raas_HoldShortApproaching", c.Runway);
                case RaasCalloutType.HoldShortStop:        return T("Raas_HoldShortStop", c.Runway);
                case RaasCalloutType.OffRoute:             return T("Raas_OffRoute", c.Taxiway);
                case RaasCalloutType.RouteComplete:        return T("Raas_RouteComplete");
                case RaasCalloutType.TurnNow:
                    if (c.Side == TurnSide.Right) return T("Raas_TurnNowRight", c.Taxiway);
                    if (c.Side == TurnSide.Left)  return T("Raas_TurnNowLeft", c.Taxiway);
                    return T("Raas_TurnNowStraight", c.Taxiway);
                case RaasCalloutType.TurnAhead:
                    if (c.Side == TurnSide.Right) return T("Raas_TurnAheadRight", c.Taxiway, m);
                    if (c.Side == TurnSide.Left)  return T("Raas_TurnAheadLeft", c.Taxiway, m);
                    return T("Raas_TurnAheadStraight", c.Taxiway, m);
                default: return "";
            }
        }
